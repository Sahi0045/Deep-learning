"""
generate_synthetic_data.py - Isolated synthetic toy data generator for unit tests only.

IMPORTANT:
  Synthetic images generated by this script use artificial color gradients and
  geometric shapes. They MUST NOT be used in final benchmark experiments and are
  explicitly rejected by data_pipeline.py when exclude_synthetic=True (the default).
  By default, this script writes only to 'synthetic_demo_data/'.
"""

import argparse
import logging
import os
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from config import cfg

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

CLASSES = cfg.data.classes

CLASS_COLORS = {
    "nonviolent":      [(100, 200, 100), (80, 180, 80), (120, 220, 120)],
    "unarmed_assault": [(220, 120, 60),  (200, 90, 40), (240, 140, 80)],
    "armed_assault":   [(180, 50, 50),   (150, 30, 30), (210, 70, 70)],
}

IMAGE_SIZE = cfg.data.image_size


def generate_class_image(class_name: str, idx: int) -> Image.Image:
    """Generate a synthetic RGB image prefixed with synthetic_ for smoke testing."""
    rng = np.random.default_rng(seed=hash((class_name, idx)) % (2**31))
    base_colors = CLASS_COLORS.get(class_name, [(128, 128, 128), (96, 96, 96)])
    c1 = np.array(base_colors[0], dtype=np.float32)
    c2 = np.array(base_colors[1 % len(base_colors)], dtype=np.float32)

    gradient = np.zeros((IMAGE_SIZE, IMAGE_SIZE, 3), dtype=np.float32)
    for row in range(IMAGE_SIZE):
        t = row / IMAGE_SIZE
        gradient[row] = (1 - t) * c1 + t * c2
    image = Image.fromarray(np.clip(gradient, 0, 255).astype(np.uint8), "RGB")
    draw = ImageDraw.Draw(image)

    for _ in range(int(rng.integers(2, 5))):
        cx = int(rng.integers(10, IMAGE_SIZE - 10))
        cy = int(rng.integers(10, IMAGE_SIZE - 10))
        r = int(rng.integers(8, 28))
        fill_color = tuple(int(v) for v in base_colors[rng.integers(0, len(base_colors))])
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=fill_color, outline=(0, 0, 0))

    img_array = np.array(image, dtype=np.float32)
    noise = rng.normal(0, 10, img_array.shape)
    image = Image.fromarray(np.clip(img_array + noise, 0, 255).astype(np.uint8), "RGB")
    return image.filter(ImageFilter.GaussianBlur(radius=1.0))


def generate_dataset(output_dir: str = "synthetic_demo_data", num_per_class: int = 20) -> None:
    """Write synthetic images to an isolated directory (never training_data/)."""
    if os.path.abspath(output_dir) == os.path.abspath(cfg.data.train_path):
        raise ValueError(
            "Refusing to write synthetic images into the verified training_data directory."
        )
    os.makedirs(output_dir, exist_ok=True)
    for class_name in CLASSES:
        class_dir = os.path.join(output_dir, class_name)
        os.makedirs(class_dir, exist_ok=True)
        for i in range(num_per_class):
            img = generate_class_image(class_name, idx=i)
            path = os.path.join(class_dir, f"synthetic_img_{i:04d}.jpg")
            img.save(path, "JPEG", quality=90)
    logger.info("Generated isolated synthetic smoke-test images in '%s'.", output_dir)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate isolated synthetic smoke-test data.")
    parser.add_argument("--output_dir", type=str, default="synthetic_demo_data")
    parser.add_argument("--num_per_class", type=int, default=20)
    args = parser.parse_args()
    generate_dataset(output_dir=args.output_dir, num_per_class=args.num_per_class)
